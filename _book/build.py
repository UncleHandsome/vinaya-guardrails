def secular(text):
    """改正文之句＋生附錄之表，同一名單為源（改一處即登一號）。"""
    n = 0
    for old, new, _r, _s in SECULAR:
        if old is None:
            continue
        c = text.count(old)
        if c:
            text = text.replace(old, new)
            n += c
        print(u"　條號%s：%s（%d 處）" % (u"外移" if c else u"空", (new or old)[:16], c))
    rows = [(r, s) for _o, _nw, r, s in SECULAR if r and s]
    blk = u"\n" + SEC_TABLE_HEAD + u"".join(u"| %s | %s |\n" % (r, s) for r, s in rows) + u"\n"
    k = text.find(u"## 附錄五")
    if k < 0:
        raise SystemExit(u"secular：附錄五之界不可得，對照表無處可插")
    print(u"世俗條號之治：正文改 %d 處｜附錄四登 %d 行（同一名單為源）" % (n, len(rows)))
    return text[:k] + blk + text[k:]

