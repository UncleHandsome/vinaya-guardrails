def make_toc(text):
    out = [u"## 【本書總目錄】（由書身實題生成・改書即改目）", u""]
    fence = False
    in_chap = False
    for l in text.split(u"\n"):
        if l.startswith(u"```"):
            fence = not fence
            continue
        if fence:
            continue
        m = re.match(r"^# 【(.+?)】$", l)
        if m:
            out.append(u"")
            out.append(u"**%s**" % m.group(1))
            in_chap = False
            continue
        m = re.match(r"^# (第[一二三四五六七八九十]+章　.+)$", l)
        if m:
            out.append(u"- %s" % m.group(1))
            in_chap = True
        elif l.startswith(u"# 終卷"):
            out.append(u"- %s" % l.lstrip("# "))
            in_chap = False
        elif l.startswith(u"## 附錄"):
            out.append(u"- %s" % l[3:])
            in_chap = False
        elif in_chap and l.startswith(u"## "):
            out.append(u"    - %s" % l[3:])
    return u"\n".join(out)



def apx_selfcheck(text):
    """附錄五之自我對帳：F-3（無從覆核清單）逐條點名 F-1 之某行，
       若 F-1 表內已無其行，則是審問幽靈——刪其條，並把序號重排，不使底冊自相殘殺。"""
    def seg(head, nxts):
        i = text.find(head)
        if i < 0:
            return None, None
        js = [text.find(x, i + 1) for x in nxts]
        js = [j for j in js if j > 0]
        return i, (min(js) if js else len(text))
    i1, j1 = seg(u"### F-1", [u"### F-2", u"### F-3"])
    i3, j3 = seg(u"### F-3", [u"### F-4", u"# 終卷"])
    if i1 is None or i3 is None:
        print(u"附錄自帳：F-1 或 F-3 之段佚，未行")
        return text
    f1 = text[i1:j1]
    body = text[i3:j3]
    kept, dropped, n = [], [], 0
    for l in body.split(u"\n"):
        m = re.match(u"^\\|\\s*([0-9]+)\\s*\\|(.*)$", l)
        if not m:
            kept.append(l)
            continue
        anchors = re.findall(u"F-1\uff08([^）]{2,40})\uff09", l)
        ghost = [a for a in anchors if a not in f1]
        if ghost:
            dropped.append(u"#%s（F-1 無此『%s』之行）" % (m.group(1), ghost[0]))
            continue
        n += 1
        kept.append(u"| %d |%s" % (n, m.group(2)))
    print(u"附錄自帳：F-3 存 %d 條｜刪幽靈條 %d：%s" % (n, len(dropped), u"／".join(dropped) or u"無"))
    if not dropped:
        return text
    return text[:i3] + u"\n".join(kept) + text[j3:]


