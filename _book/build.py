CASE_SEC_H = re.compile(u"^## [^\n]*(案例|現行犯|案發現場|判例)[^\n]*$", re.M)


def splice(pre, txt):
    """章內案例群須歸入本章自宣『案例解碼』之節——昔全數堆於末節（結語之下），
       遂成『宣案例之節空無一案、結語之下反堆四十案』之接縫。無此宣節者仍置章尾。"""
    if not txt:
        return [pre]
    m = CASE_SEC_H.search(pre)
    if not m:
        # 無『案例解碼』之節可歸者（如第十四章・其案例節在第十五章），另立一節以領之，
        # 不使案例掛於【本書之斷】或結語之下；節號仍由『節序之治』統一編次。
        return [pre, u"## 一、案例解碼\n\n" + txt]
    i = m.end()
    return [pre[:i] + u"\n\n" + txt, pre[i:]]


