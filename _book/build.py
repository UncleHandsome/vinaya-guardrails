def rebox(text):
    """樹圖之葉與三枝之列：去其定額，並依框角之幾何重建該兩行（舊冊此兩行比框角寬六列，
       其作者以半形算「100 片」之寬，今一并歸正——左右界與 ┌┐ 之行一字不差）。"""
    lines = text.split(u"\n")
    geo = None
    for i, l in enumerate(lines):
        if u"100 片法相之葉" in l or u"遮止 45 ｜" in l:
            for j in range(i - 1, max(0, i - 6), -1):
                if lines[j].strip().startswith(u"┌"):
                    c = lines[j]
                    a, z = c.find(u"┌"), c.find(u"┐")
                    geo = (c[:a], dwidth(c[a + 1:z]), c[z + 1:])
                    break
            break
    if not geo:
        return text, 0
    pre, body_w, tail = geo
    out, n = [], 0
    for l in lines:
        m = re.match(u"^\\s*│\\s*(.*?)\\s*│", l)
        hit = None
        for old, new in BOX_LEAF:
            if old in l:
                hit = new
                break
        if m and hit:
            inner = u" " + m.group(1).replace(
                [o for o, _ in BOX_LEAF if o in l][0], hit).strip()
            inner += u" " * max(0, body_w - dwidth(inner))
            out.append(pre + u"│" + inner + u"│" + tail)
            n += 1
            continue
        out.append(l)
    return u"\n".join(out), n


