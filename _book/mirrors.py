def _log(k, x):
    FRAME_LOG[k] = FRAME_LOG.get(k, 0) + 1
    return k, fix_q(x)


def fix_q(x):
    """全段之角引號須成對：多出的單邊引號一律鋤去（尺十一之破口，不出自冊身）。"""
    for a, b in ((u"「", u"」"), (u"『", u"』")):
        while x.count(a) > x.count(b):
            i = x.rfind(a)
            x = x[:i] + x[i + 1:]
        while x.count(b) > x.count(a):
            i = x.find(b)
            x = x[:i] + x[i + 1:]
    return x


def make_mirror(fa_text, idx):
    """就本案『法相剖析』轉一機位：取其骨幹，換第二人稱；骨幹之外不增一義。"""
    import re
    s = re.sub(u"\\*\\*", u"", fa_text or u"")
    s = re.sub(u"^\\s*[0-9]+[.、]\\s*", u"", s, flags=re.M)
    tries = [
        (u"甲・不是而是", u"不是(.{2,26}?)，而是(.{3,34}?)[。；]", (1, 2),
         u"你且自照：這條戒若要防的當真是「%s」，何必寫得這樣細？它防的是「%s」——%s"),
        (u"乙・最難", u"最(難|危險|要緊|不易)的是(.{2,30}?)[。；，]", (2,),
         u"你讀這一句，多半先在心裡點了別人的名——「%s」這回事，你以為總在別人身上。%s"),
        (u"丙・以為", u"以為(.{2,28}?)[。；，]", (1,),
         u"你以為「%s」，便算得了清淨？律在此所問的不是這一句說辭，是你落下之前那一念如何自處。%s"),
        (u"己・而在", u"不在(.{2,24}?)，(而|也)在(.{3,30}?)[。；！？]", (1, 3),
         u"你以為此條所禁在「%s」？律在此管的卻是「%s」。%s"),
        (u"丁・任何", u"(任何|凡是|一切)[^。；，「」『』]{2,20}?(的人|團體|組織|場合)", (0,),
         u"你把這病歸給「%s」，卻忘了條文所對的從來不是別處，正是你此刻這一念。%s"),
    ]
    for n, (key, pat, grs, tpl) in enumerate(tries):
        m = re.search(pat, s)
        if not m:
            continue
        frag = [bal(m.group(g)) for g in grs]
        if any(len(x) < 4 for x in frag):
            continue
        cl = CLOSER[(idx + n) % 3]
        if len(frag) == 1:
            return _log(key, tpl % (frag[0], cl))
        return _log(key, tpl % (tuple(frag) + (cl,)))
    # 落於通式：取剖析中最長一項之首句（截於句讀與括號之外，至多二十二字），只換一位，不增一義
    its = [re.sub(u"^\\s*[*\\-]\\s*", u"", x).strip() for x in re.split(u"\\n+", s)]
    its = [x for x in its if len(bal(x)) > 24]
    if not its:
        return u"", u""
    seg = u""
    for it in sorted(its, key=len, reverse=True):
        cand = []
        for piece in re.split(u"[：]", bal(it)):
            for sent in re.split(u"[。！？]", piece.strip()):
                sent = bal(sent)
                if len(sent) > 34:
                    cuts = [m.start() for m in re.finditer(u"[，；]", sent[:34])]
                    sent = bal(sent[:max(cuts) if cuts and max(cuts) > 9 else 34])
                if 8 <= len(sent) <= 34:
                    cand.append(sent)
        if cand:
            seg = max(cand, key=len)
            break
    if len(seg) < 8:
        return u"", u""
    return _log(u"戊・通式", u"你讀此案，多半是在看別人的失手；且把這一句留給自己：「%s」——%s"
                % (seg, CLOSER[idx % 3]))
