def bal(x):
    """片段之角引號須自閉：「」降為『』，不成對者鋤去，尾端句讀除去。"""
    x = (x or u"").strip(u"『』「」\u3000").strip(u"，、。；：")
    x = x.replace(u"「", u"『").replace(u"」", u"』")
    while x.count(u"『") > x.count(u"』"):
        i = x.rfind(u"『")
        x = x[:i] if i > 0 else u""
    while x.count(u"』") > x.count(u"『"):
        i = x.index(u"』")
        x = x[i + 1:]
    return x.strip(u"，、。；：『』 　—－～-")


def pick(x):
    return bal(x)


