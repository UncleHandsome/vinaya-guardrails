# -*- coding: utf-8 -*-
"""章次地圖・唯一法源（`merge_build` 改指針用，`merge_check` 核落地用）。

第三十八輪一日之內三度因『兩處各寫一套』而誤判：序數解析器漂移漏掛 59 標、
落地尺不知改寫值遂把隨改之指針算成佚文。故地圖只此一處，改處即改尺。
"""
import re

V_MAP = {u"第一章": u"第四章", u"第二章": u"第五章", u"第三章": u"第六章",
         u"第五章": u"第二十一章", u"第六章": u"第七至十三章",
         u"第七章": u"附錄三", u"第八章": u"卷末・工具箱", u"第九章": u"第二十七章"}
H_MAP = {u"第五章": u"第七章", u"第六章": u"第八章", u"第七章": u"第九章",
         u"第八章": u"第十章", u"第九章": u"第十一章", u"第十章": u"第十二章",
         u"第十一章": u"第十三章", u"第十二章": u"第十四、十五章", u"第十三章": u"第十六章",
         u"第十四章": u"第十七章", u"第十五章": u"第十八章", u"第十六章": u"第二十二章",
         u"第十七章": u"第二十三章", u"第十八章": u"第二十四章", u"第十九章": u"第二十五章",
         u"第二十章": u"第二十六章"}          # 護欄第一～四章同名，故不列（自指不改）
SPLIT = {u"第四章": (u"第十九章", u"第二十章", u"第五節"),     # 框架第四章 → 19・20 章
         u"第十章": (u"第十二章", u"第二十章", u"七滅諍")}     # 護欄第十章 → 12・20 章
# 拆章之後，兩章各自重編其節序（第十九章失其第五節、第二十章唯餘第五節）——
# 不重編則印面見「章下首行即第五節」之斷頭，與「一・二・三・四・六・七」之跳號。
SEC_RENUM = {u"第十九章": {u"第六節": u"第五節", u"第七節": u"第六節"},
             u"第二十章": {u"第五節": u"第一節"}}


def pair(a, b):
    """兩章合指之reader形：『第十九、二十章』（舊作『第十九章（另見第二十章）』，
    正式文本中絕不可留此除錯語法）。"""
    return u"第%s、%s章" % (a[1:-1], b[1:-1])

VALS = sorted(set(list(V_MAP.values()) + list(H_MAP.values()) +
                  [x for t in SPLIT.values() for x in t[:2]]), key=len, reverse=True)
NUM = re.compile(u"第[一二三四五六七八九十]+章(?:第[一二三四五六七八九十]+節)?")
SECONLY = re.compile(u"第[一二三四五六七八九十]+節")      # 節號重編後兩側皆不認號，只比文身
SEE = re.compile(u"（另見第[一二三四五六七八九十]+章）")
PAIR = re.compile(u"第[一二三四五六七八九十]+、[一二三四五六七八九十]+章(?:第[一二三四五六七八九十]+節)?")
# 產器自掛之腳手架：比對時同須剷除，否則「隨改」被誤計為「佚文」
MARK = re.compile(u"〔指針待判〕|〔指針已重算・待復核〕|〔待校[^〕]*〕|〔待寫[^〕]*〕|（素材卡）")


NAMES = [(u"頻婆娑羅", u"瓶沙"), (u"優填王", u"憂陀延王"), (u"目犍連", u"目連"),
         (u"給孤獨長者", u"給孤獨食")]          # 正名令之對照（build 依此改文，尺依此歸形）


def strip_refs(s):
    """剷盡『指針之形』：先歸正名之形，次剷改寫後之章名（值）與合指之式，再剷舊章號——
    落地尺以此比文身，不比號，亦不比已奉令統一之名。"""
    for bad, good in NAMES:
        s = s.replace(bad, good)
    for v in VALS:
        s = s.replace(v, u"")
    s = PAIR.sub(u"", s)
    return MARK.sub(u"", SECONLY.sub(u"", NUM.sub(u"", SEE.sub(u"", s))))


def skeleton(s):
    """只留漢字之骨（比對用）。"""
    return re.sub(r"[^一-鿿]", u"", strip_refs(s))
