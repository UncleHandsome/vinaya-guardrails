NEWTXT = []


def sub(idx, old, new, tag):
    """第 idx 行（1 起）須恰含 old 一次，換為 new。"""
    t = L[idx - 1]
    assert t.count(old) == 1, (u"命中數不符：" + tag, idx, t.count(old))
    L[idx - 1] = t.replace(old, new)
    assert L[idx - 1].count(new) >= 1, (u"未寫入：" + tag)
    NEWTXT.append(L[idx - 1])
    print(u"改 %s @L%d（舊 1 中・新 %d 字）" % (tag, idx, len(new)))


def tail(idx, add, tag):
    t = L[idx - 1]
    assert t.endswith(u"**"), (u"尾形不符：" + tag, t[-12:])
    L[idx - 1] = t + add
    NEWTXT.append(add)
    print(u"添句 %s @L%d（+%d 字）" % (tag, idx, len(add)))


def ins_after(idx, lines, tag):
    assert L[idx] == u"", (u"下一行非空：" + tag, repr(L[idx][:30]))
    assert L[idx + 1].startswith(u"---"), (u"再下行非分隔線：" + tag, L[idx + 1][:20])
    for t in lines:
        assert u"・" not in t and u"！" not in t, (u"禁用字形：" + tag)
        for m in re.finditer(u"「\\*\\*([^」\\n]*)\\*\\*」", t):
            assert _tk.VINAYA.find(_tk.norm(m.group(1))) >= 0, (u"逐字無據：" + tag, m.group(1)[:20])
    NEWTXT.extend(lines)
    L[idx + 1:idx + 1] = lines + [u""]
    print(u"插入 %s @L%d 後 +%d 行" % (tag, idx, len(lines) + 1))


