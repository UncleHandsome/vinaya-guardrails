    bw = rc + rw
    st = ((6 + bw) // 2) // 2 * 2
    out = [pad("", st - dw(MX_TITLE) // 2) + MX_TITLE, pad("", st) + "│",
           " " * 6 + "┌" + "─" * ((st - 8) // 2) + "┴" + "─" * ((bw - st - 4) // 2) + "┐",
           pad("", 6) + "▼" + pad("", st - 8) + "▼" + pad("", bw - st - 4) + "▼",
           pad("", lc) + MX_HL + pad("", rc - lc - dw(MX_HL)) + MX_HR]
    for a, b in zip(MX_LL, MX_LR):
        out.append(pad("", lc) + a + pad("", rc - lc - dw(a)) + b)
    out.append(pad("", lc + 1) + "│" + pad("", rc - lc - 3) + "│")
    for t, a, b in zip(MX_TREE, MX_TL, MX_TR):
        out.append(pad("", lc - 4) + t + " " + pad(a, lw) + " " + MX_ARROW + " " + b)
    out.append(pad("", st) + "▲")
    out.append(pad("", st) + "│")
    for x in MX_FOOT:
        out.append(pad("", st - 12) + x)
    wide = [i for i, x in enumerate(out) if dw(x.rstrip()) > bw]
    if wide:
        raise SystemExit("對位圖逾寬：%s" % [(i, out[i][:16]) for i in wide])
    if len({dw(x[:x.find(MX_ARROW)]) for x in out if MX_ARROW in x}) != 1:
        raise SystemExit("對位圖箭頭未齊")
    return out


