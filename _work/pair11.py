def dw(s):
    n = 0
    for c in s:
        o = ord(c)
        if 0x2E80 <= o <= 0x9FFF or 0xAC00 <= o <= 0xF7AF or 0xFF01 <= o <= 0xFF60 \
           or 0x3000 <= o <= 0x303F or 0x2500 <= o <= 0x27BF:
            n += 2
        else:
            n += 1
    return n


def pad(s, cells):
    if dw(s) > cells:
        raise SystemExit("格數溢出：%r（%d > %d）" % (s[:20], dw(s), cells))
    return s + " " * (cells - dw(s))


def mx_fence():
    """二欄對位圖：左欄起 11 格，箭頭居其右，右欄起 rcol；主幹置全圖之中——一切以格數算，不手排。"""
