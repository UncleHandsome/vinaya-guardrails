def main():
    apply = u'apply' in sys.argv
    raw = io.open(SRC, encoding=u'utf-8-sig').read()
    L = raw.replace(u'\r\n', u'\n').split(u'\n')
    print(u'正本｜%d 行・sha256 %s' % (len(L), hashlib.sha256(raw.encode(u'utf-8')).hexdigest()[:12]))
    out = list(L)
    for tag, old, new, want in REPS:
        n = sum(x.count(old) for x in out)
        if n != want:
            raise AssertionError(u'%s｜錨見 %d 次（須 %d）：%s' % (tag, n, want, old[:26]))
        out = [x.replace(old, new) for x in out]
        print(u'  ✓ %s' % tag)
    k = next(i for i, l in enumerate(out) if l.rstrip() == ROW0)
    if out.count(ROW0) != 1:
        raise AssertionError(u'子・人名表末行之錨非一（得 %d）' % out.count(ROW0))
    out[k + 1:k + 1] = ROWS
    print(u'  ✓ 子・人名表補九行（L%d 後，總行數 16➔%d）' % (k + 1, 16 + len(ROWS)))
    txt = u'\n'.join(out)
    if not apply:
        print(u'———— 乾跑畢（加 apply 方落刀）・行 %+d・字 %+d' % (len(out) - len(L), len(txt) - len(raw)))
        return 0
    shutil.copyfile(SRC, os.path.join(WORK, u'r277fix2.bak'))
    io.open(SRC, u'w', encoding=u'utf-8', newline=u'\n').write(txt)
    new = io.open(SRC, encoding=u'utf-8').read()
    print(u'落刀｜備份 r277fix2.bak｜%d 行・%d B・sha256 %s' % (
        new.count(u'\n') + 1, len(new.encode(u'utf-8')), hashlib.sha256(new.encode(u'utf-8')).hexdigest()[:12]))
    return 0 if new == txt else 2


if __name__ == u'__main__':
    sys.exit(main())
