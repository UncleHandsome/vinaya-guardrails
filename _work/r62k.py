"""第六十二輪・款級債之收尾（七條，逐條以舊冊款題對今冊款題而證）。

舊冊諸節之款標與今冊逐字相同、序亦不動（舊十九→今十四・舊二十一→今十六・舊二十七→今十七），
故凡回錨得『舊章-舊節-舊款』者，其今靶序即可直取。七條之據：
  L3186 第十一章第一節第一款 → 第十六章第一節第一款（舊21-1-1『戒體損益四態模型』，本句正言『戒體損益見』）
  L3197 第十二章第三節第四款 → 第十七章第六節第四款（舊27-3-4『時效紅線與轉軌救濟』，本句言『開許日落審計』）
  L3396 第十章第四節第六款   → 第十四章第四節第六款（舊19-4-6『非法羯磨之平反阻斷與宣告確認程序』）
  L17832 第十章第二節第六款  → 第十四章第二節第六款（舊19-2-6 款題即本句所引『舉罪學・善覓諍』，一字不差）
  L19530 第十二章第四節第三款 → 第十七章第七節第三款（舊27-4-3『數位虛擬空間之結界延伸』，本句在科技倫理卡）
  L21047 第十二章第四節第一款 → 第十七章第七節第一款（舊27-4-1『重大刑事犯罪之強制通報』，石蜜案屬販人重罪）
  L1326  第十四章第六節第三款 → 第十四章第六節（今節唯二款，無從實證第三款，削款留節——節級為真）
"""
import io
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
P = os.path.join(ROOT, u"佛陀的護欄_重構版.md")
TSV = os.path.join(ROOT, u"_book", u"款級待裁.tsv")
LED = os.path.join(ROOT, u"_book", u"款級待裁.txt")
L = io.open(P, encoding="utf-8-sig").read().replace("\r\n", "\n").split(u"\n")
FIX = [(3186, u"第十一章第一節第一款", u"第十六章第一節第一款"),
       (3197, u"第十二章第三節第四款", u"第十七章第六節第四款"),
       (3396, u"第十章第四節第六款", u"第十四章第四節第六款"),
       (17832, u"第十章第二節第六款", u"第十四章第二節第六款"),
       (19530, u"第十二章第四節第三款", u"第十七章第七節第三款"),
       (21047, u"第十二章第四節第一款", u"第十七章第七節第一款"),
       (1326, u"第十四章第六節第三款", u"第十四章第六節")]
n = 0
for i, old, new in FIX:
    if old not in L[i - 1]:
        print(u"  未中 L%d %s" % (i, old))
        continue
    L[i - 1] = L[i - 1].replace(old, new, 1)
    n += 1
    print(u"  改 L%-6d %-14s → %s" % (i, old, new))
io.open(P, "w", encoding="utf-8", newline="\n").write(u"\n".join(L))
print(u"落筆 %d／%d" % (n, len(FIX)))
