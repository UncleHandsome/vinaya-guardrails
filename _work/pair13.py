def clean(new, tag):
    if PS.flag(new):
        raise SystemExit("%s 簡形閘：%s 於『%s』" % (tag, PS.hits(new), new[:44]))
    for wd in re.findall(r"[A-Za-z]{2,}", new):
        raise SystemExit("%s 夾英文『%s』於『%s』" % (tag, wd, new[:44]))


def verbatim_chk(text, tag, hard=True):
    """凡「…」式樣須在本地語料見形（折疊＋只留漢字）；他典亦入證。"""
    hay = cjk(V)
    for k, v in _tk.OTHER.items():
        s = v if isinstance(v, str) else v.decode("utf-8", "ignore")
        hay += cjk(s)
    bad, n = [], 0
    for line in text.split(LF):
        for m in re.finditer(r"「([^」]{4,})」", line):
            left = line[max(0, m.start() - 46):m.start()]
            if not (u"《" in left or u"本地" in left
                    or re.search(u"卷第?[〇一二三四五六七八九十百][0-9]*", left)):
                continue
            n += 1
            if cjk(m.group(1)) not in hay:
                bad.append(m.group(1)[:30])
    if bad and hard:
        raise SystemExit("%s 逐字閘：%d 段無形於語料 ➔ %s" % (tag, len(bad), bad))
    if bad:
        print("  軟報（舊帳，本刀不動）：%s 有 %d 段掛式樣而未見形於語料：%s" % (tag, len(bad), bad[:12]))
    return n


def main():
    for src in (F1, F2):
        raw = src.read_bytes().decode("utf-8-sig")
        nl = CRLF if CRLF in raw else LF
        L = raw.replace(CRLF, LF).split(LF)
        before = len(L)
        print("=" * 72)
        print("■", src.name[:12])
        for fsrc, mode, anchor, seg, tag in BLOCKS:
            if fsrc != src:
                continue
            if sum(1 for x in seg if len(x) > 16 and x in L) >= 2:
                print("  %s 已在檔（重入之護）" % tag)
                continue
            i = [k for k, l in enumerate(L) if l.strip() == anchor.strip()]
            if len(i) != 1:
                raise SystemExit("%s 錨非唯一：%r → %d 行" % (tag, anchor[:24], len(i)))
            i = i[0]
            if mode == "before":
                while i > 0 and (not L[i - 1].strip() or L[i - 1].strip() in ("---", "***")):
                    i -= 1
                pos = i
            else:
                pos = i + 1
            for x in seg:
                clean(x, tag)
            verbatim_chk(LF.join(seg), tag)
            L[pos:pos] = ([""] + seg + [""]) if mode == "before" else ([""] + seg)
            print("  %s 落於 L%d（%d 行）" % (tag, pos + 1, len(seg) + 2))
        txt = LF.join(L)
        soft = verbatim_chk(txt, src.name[:6], hard=False)
        bad = [(k + 1, PS.hits(l)) for k, l in enumerate(L) if PS.flag(l)]
        if bad:
            raise SystemExit("全檔簡形閘：%s" % bad[:5])
        print("  逐字閘：新落之塊俱就地見形 ✓")
        print("  行數 %d ➔ %d" % (before, len(L)))
        if not W:
            print("  （試跑：未落盤）")
            continue
        (ROOT / "_archive/備份/AI清理前" / (src.name + ".pre_a13")).write_bytes(raw.encode("utf-8"))
        data = nl.join(L).encode("utf-8")
        src.write_bytes(data)
        print("  落盤：SHA %s ➔ %s" % (hashlib.sha256(raw.encode()).hexdigest()[:12],
                                        hashlib.sha256(data).hexdigest()[:12]))


if __name__ == "__main__":
    main()
