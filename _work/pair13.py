def harvest(needle, back=0, fwd=0, where=None, tail=0):
    """於原檔（帶標點）求 needle（以 CJK 折叠形匹配），回截得之原文與出處名。"""
    n = cjk(needle)
    for nm, raw in FILES:
        if where and where not in nm:
            continue
        s = raw if isinstance(raw, str) else raw.decode("utf-8", "ignore")
        keep, idx = [], []
        for i, c in enumerate(s):
            if cjk(c):
                keep.append(TAB.get(c, c))
                idx.append(i)
        k = cjk("".join(keep)).find(n)
        if k < 0:
            continue
        a, b = idx[k], idx[k + len(n) - 1] + 1
        seg = s[max(0, a - back):b + fwd + tail]
        return seg.replace("「", "『").replace("」", "』"), nm
    raise SystemExit("逐字不可得（不採為律據）：%s" % needle[:24])


