def gates(block, tag):
    err = []
    for l in block:
        for m in RX_CITE.finditer(l):
            bad = verbatim_bad(m.group(1))
            if bad:
                err.append("逐字・%s「%s」缺形「%s」" % (tag, m.group(1)[:22], bad[0]))
        insid = [(x.start(1), x.end(1), x.group(1)) for x in RX_PAREN.finditer(l)]

        def span_of(pos):
            for a, b, body in insid:
                if a <= pos < b:
                    return body
            return None
        for x in re.finditer(r"[A-Za-z]{2,}", l):
            w = x.group(0)
            if w in ("text", "pre"):
                continue
            body = span_of(x.start())
            if body is None:
                err.append("英文・%s 夾「%s」於「%s」" % (tag, w, l.strip()[:32]))
                continue
            for tok in RX_LAT.findall(body):
                t = tok.strip()
                if t and t not in TRANSLIT and not all(y in TRANSLIT for y in t.split()):
                    err.append("標音非白名單・%s「%s」於（%s）" % (tag, t, body[:22]))
        h = PS.hits(l)
        if h:
            err.append("簡形・%s 犯『%s』「%s」" % (tag, h, l[:32]))
    return err


