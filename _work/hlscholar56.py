ins = 0
for i, (old, new, want) in enumerate(CUTS, 1):
    got = raw.count(old)
    if got != want:
        raise SystemExit(u"靶 %d 命中 %d（須 %d），未動一字：%s" % (i, got, want, old[:34]))
    if u"\n" in new.replace(u"\r\n", u""):
        raise SystemExit(u"靶 %d 之新文帶孤 LF（會生 CR-CRLF 之疊）——中止。" % i)
    ins += (new.count(u"\r\n") - old.count(u"\r\n")) * want
    raw = raw.replace(old, new)
    print(u"刀%2d｜命中 %d ✓｜%4d→%4d字｜插行 %+d｜%s"
          % (i, want, len(old), len(new), new.count(u"\r\n") - old.count(u"\r\n"), old[:24]))
if raw.count(u"\r\n") != n_cr + ins:
    raise SystemExit(u"CRLF 增量不合（須 %+d，今 %+d）——未寫檔。"
                     % (ins, raw.count(u"\r\n") - n_cr))
