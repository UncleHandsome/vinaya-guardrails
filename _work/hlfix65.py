def cw(s):
    return sum(2 if ord(c) > 0x2E80 else 1 for c in s)


def check_fence(tag, block):
    mx = max(cw(x) for x in block)
    assert mx <= 72, u"%s：最寬 %d 格越界" % (tag, mx)
    for x in block:
        assert x.strip(), u"%s：圍欄內有純空行（pandoc 會併段）" % tag
    print(u"  %s：%d 行｜最寬 %d 格 ✓" % (tag, len(block), mx))


