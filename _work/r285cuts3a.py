# -*- coding: utf-8 -*-
"""285・批三之刀（附錄六改號）：〔補遺 29〜44（除 36）〕➔〔調部深描 01〜15〕，
   前言・目錄・凡例・全書指針同輪改齊。用法：python -X utf8 _work/r285cuts3a.py [--apply]"""
import io
import re
import shutil
import sys

P = u'ver39四分律_起心動念心智分析框架_修正版.md'
APPLY = u'--apply' in sys.argv
S = io.open(P, encoding=u'utf-8').read()
NL = u'\r\n' if u'\r\n' in S else u'\n'
T = S.replace(u'\r\n', u'\n')
MAP = {29: u'01', 30: u'02', 31: u'03', 32: u'04', 33: u'05', 34: u'06', 35: u'07',
       37: u'08', 38: u'09', 39: u'10', 40: u'11', 41: u'12', 42: u'13', 43: u'14', 44: u'15'}
LOG = []


def rep(old, new, label, x=1):
    c = T.count(old)
    assert c == x, u'【%s】命中 %d 見・期 %d 見' % (label, c, x)
    LOG.append(u'%-34s 命中 %d' % (label, c))
    return T.replace(old, new, x)


# 一、15 則之題（唯此 15 行匹配，故以正則替換，逐一印其映射）
_h = re.findall(u'(?m)^### 〔補遺 (\\d+)〕', T)
assert _h == [u'29', u'30', u'31', u'32', u'33', u'34', u'35', u'37', u'38', u'39',
              u'40', u'41', u'42', u'43', u'44'], u'標題序列非期：%s' % _h
T, n = re.subn(u'(?m)^### 〔補遺 (\\d+)〕',
               lambda m: u'### 〔調部深描 %s〕' % MAP[int(m.group(1))], T)
LOG.append(u'%-34s 改 %d 題' % (u'十五則之 H3 標題改號', n))

# 二、凡例兩處
T = rep(u'附錄六（十五則補遺）於【佛陀判語】下自標 `◎原典` 以起引文',
        u'附錄六（調部深描十五則）於【佛陀判語】下自標 `◎原典` 以起引文', u'凡例【原典層】')
T = rep(u'**案例與補遺之編號**（〔案例 01〕之屬；連寫可省其類名，如〔補遺29〕〔31〕〔32〕）',
        u'**案例與深描之編號**（〔案例 01〕之屬；連寫可省其類名，如〔調部深描 01〕〔02〕〔03〕）',
        u'凡例〔…〕之兩用')

# 三、卷首目錄
T = rep(u'（上・下兩篇，〔補遺 29〕至〔補遺 44〕十五則極限判例：',
        u'（上・下兩篇，〔調部深描 01〕至〔15〕十五則極限判例：', u'卷首目錄・附錄六條')

# 四、全書兩處指針
T = rep(u'不作為犯之保證人責任見〔補遺 29〕', u'不作為犯之保證人責任見〔調部深描 01〕',
        u'第三章・止犯不坐別住')
T = rep(u'（如〔補遺43〕）', u'（如〔調部深描 14〕）', u'第六章・兩舌豁免但書')

# 五、附錄六前言（缺號之說自此消失，故整句重鑄）
T = rep(u'> **此十五則與第六章之表裡，先說在前頭**：其中十則（〔補遺29〕〔31〕〔32〕〔33〕〔34〕'
        u'〔35〕〔37〕〔41〕〔42〕〔44〕）正文未立其卡，判例之數以正文 **102 則**為準；'
        u'（編次虛一補遺 36 之位，乃歷次整理所遺之缺號，非漏印，檢索者勿疑）；'
        u'另五則（〔補遺30〕〔38〕〔39〕〔40〕〔43〕）與正文某卡表裡',
        u'> **此十五則與第六章之表裡，先說在前頭**：其中十則（〔調部深描 01〕〔03〕〔04〕〔05〕'
        u'〔06〕〔07〕〔08〕〔12〕〔13〕〔15〕）正文未立其卡，判例之數以正文 **102 則**為準；'
        u'另五則（〔調部深描 02〕〔09〕〔10〕〔11〕〔14〕）與正文某卡表裡',
        u'附錄六前言・表裡句')

# 六、下篇導言與篇末歸位句
T = rep(u'完整呈交調部邊緣疑難判例之第七至第十五則（**〔補遺 38〕至〔補遺 44〕**，共七案）',
        u'完整呈交調部邊緣疑難判例之第九至第十五則（**〔調部深描 09〕至〔15〕**，共七案）',
        u'下篇導言')
T = rep(u'**「調部邊緣疑難判例法十五則深描（補遺 29～35，37～44）」**已全數完整歸位',
        u'**「調部邊緣疑難判例法十五則深描（〔調部深描 01〕〜〔15〕）」**已全數完整歸位',
        u'篇末歸位句')

print(u'\n'.join(LOG))
print(u'校：『補遺』今 %d 見・『調部深描』%d 見・行數 %+d' % (
    T.count(u'補遺'), T.count(u'調部深描'),
    len(T.split(u'\n')) - len(S.split(u'\n'))))
assert T.count(u'〔補遺') == 0, u'仍有舊式〔補遺…〕指針'
assert len(re.findall(u'(?m)^### 〔調部深描 \\d+〕', T)) == 15

if APPLY:
    shutil.copyfile(P, u'_archive/備份/ver39.pre285c.md')
    io.open(P, 'w', encoding=u'utf-8', newline=NL).write(T)
    print(u'已寫入・備份 _archive/備份/ver39.pre285c.md')
else:
    print(u'（試跑・未寫檔）')
