def append(path, text, guard):
    s = io.open(path, encoding=u'utf-8-sig').read()
    if guard in s:
        print(u'%s：已入帳，不重出' % os.path.basename(path))
        return
    if not APPLY:
        print(u'%s：乾跑・待追加 %d 字（錨『%s』未見）' % (os.path.basename(path), len(text), guard))
        return
    io.open(path, 'a', encoding=u'utf-8').write(text.lstrip(u'\n'))
    back = io.open(path, encoding=u'utf-8-sig').read()
    print(u'%s：追加訖・今 %d 行・含錨=%s' % (os.path.basename(path), len(back.split(chr(10))), guard in back))


