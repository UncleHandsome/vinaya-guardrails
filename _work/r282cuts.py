def rep(old, new, n=1, label=u''):
    global T
    c = T.count(old)
    assert c == n, u'[%s] 錨命中 %d 處（期 %d）：%s' % (label, c, n, old[:44])
    T = T.replace(old, new, n)
    print(u'  刀 %s：%s ➔ %s' % (label, old[:26], new[:26]))


