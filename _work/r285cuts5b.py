NL = u'\r\n' if u'\r\n' in S else u'\n'
T = S.replace(u'\r\n', u'\n')
LOG = []


def rep(old, new, label):
    global T
    c = T.count(old)
    assert c == 1, u'【%s】命中 %d 見・期 1' % (label, c)
    LOG.append(u'%-28s 命中 1' % label)
    T = T.replace(old, new, 1)


