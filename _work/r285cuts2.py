def rep(old, new, label, x=1, y=None):
    if isinstance(x, int):
        lab2, n = (y or label), x
    else:
        lab2, n = x, y or 1
    c = T.count(old)
    assert c == n, u'【%s】命中 %d 見・期 %d 見' % (lab2, c, n)
    LOG.append(u'%-30s 命中 %d' % (lab2, c))
    return T.replace(old, new, n)


