def strip_pagenum(txt):
    """頁碼乃独立一行之純數字（或卷首之羅馬字）；折去所有空白後會黏進句內——
    第 191 輪實測：『…或經當事人』與『書面同意者…』跨頁，中間黏入頁碼 314，遂偽報『未見』。
    只剝每頁**首兩行與末兩行**之純碼行（頁眉頁腳之所在）；內容行中戒數、條號一概不動。"""
    ls = txt.split(u'\n')
    for i in (0, 1, len(ls) - 1, len(ls) - 2):
        if 0 <= i < len(ls) and PN.match(ls[i]):
            ls[i] = u''
    return u'\n'.join(ls)


