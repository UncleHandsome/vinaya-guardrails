RX_CITE = re.compile(r"\*\*「(.+?)」\*\*", re.S)
RX_LAT = re.compile(r"[A-Za-zÀ-ÿĀ-ſḀ-ỿ][A-Za-zÀ-ÿĀ-ſḀ-ỿ ·\-]*")
RX_PAREN = re.compile(r"（([^（）]*)）")
# 標音白名單（第三令之界：漢譯律學之標音留，西洋學科之名剝——名單即本卡有意用之轉寫）
TRANSLIT = {"Ariṭṭha", "Thullanandā", "Pilindavaccha", "Vāsanā"}


def gates(block, tag):
    err = []
    for l in block:
        for m in RX_CITE.finditer(l):
            bad = verbatim_bad(m.group(1))
            if bad:
                err.append("逐字・%s「%s」缺形「%s」" % (tag, m.group(1)[:24], bad[0]))
        insid = [(m.start(1), m.end(1), m.group(1)) for m in RX_PAREN.finditer(l)]

        def span_of(pos):
            for a, b, body in insid:
                if a <= pos < b:
                    return body
            return None
        for m in re.finditer(r"[A-Za-z]{2,}", l):
            w = m.group(0)
            if w in ("text", "pre"):
                continue
            body = span_of(m.start())
            if body is None:
                err.append("英文・%s 夾「%s」於「%s」" % (tag, w, l.strip()[:34]))
                continue
            for tok in RX_LAT.findall(body):
                t = tok.strip()
                if t and t not in TRANSLIT and not all(x in TRANSLIT for x in t.split()):
                    err.append("標音非白名單・%s「%s」於（%s）" % (tag, t, body[:24]))
        h = PS.hits(l)
        if h:
            err.append("簡形・%s 犯『%s』「%s」" % (tag, h, l[:34]))
    return err


