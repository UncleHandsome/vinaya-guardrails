def clean(new, tag):
    if PS.flag(new):
        raise SystemExit("%s 簡形閘攔下：%s 於『%s』" % (tag, PS.hits(new), new[:40]))
    for wd in re.findall(r"[A-Za-z]{2,}", new):
        if wd not in ("text", "pre"):
            raise SystemExit("%s 夾英文『%s』於『%s』" % (tag, wd, new[:40]))


def gate(seg, tag, lim=120):
    """兩閘：簡形／夾英文（逐行）＋圍欄內之逾寬（散文行自然流水，不受格限）。"""
    inf = False
    for x in seg:
        clean(x, tag)
        if x.startswith(FENCE):
            inf = not inf
            continue
        if inf and dw(x.rstrip()) > lim:
            raise SystemExit("%s 圍欄逾寬 %d＞%d：%r" % (tag, dw(x.rstrip()), lim, x[:26]))


def one(L, needle, tag):
    k = [i for i, l in enumerate(L) if l.strip() == needle.strip()]
    if len(k) != 1:
        k = [i for i, l in enumerate(L) if needle in l]
    if len(k) != 1:
        raise SystemExit("%s 錨非唯一：%r → %d 行" % (tag, needle[:26], len(k)))
    return k[0]


def save(src, raw, L, nl, tag):
    bad = [(i + 1, PS.hits(l)) for i, l in enumerate(L) if PS.flag(l)]
    if bad:
        raise SystemExit("%s 全檔簡形閘：%s" % (tag, bad[:5]))
    print("  %s 行數 %d ➔ %d・簡形 0 ✓" % (tag, len(raw.replace(CRLF, LF).split(LF)), len(L)))
    if not W:
        print("  （試跑：未落盤）")
        return
    (ROOT / "_archive/備份/AI清理前" / (src.name + ".pre_a12")).write_bytes(raw.encode("utf-8"))
    data = nl.join(L).encode("utf-8")
    src.write_bytes(data)
    print("  落盤：SHA %s ➔ %s" % (hashlib.sha256(raw.encode()).hexdigest()[:12],
                                    hashlib.sha256(data).hexdigest()[:12]))


