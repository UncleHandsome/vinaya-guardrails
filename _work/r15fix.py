def line_of(frag, tag):
    """全檔唯一命中 frag 之行，回傳其 1 起行號。"""
    ns = [i + 1 for i, t in enumerate(ORIG) if frag in t]
    assert len(ns) == 1, (u"命中數不符：" + tag, ns)
    return ns[0]


def append(idx, frag, add, tag):
    n = line_of(frag, tag)
    assert n == idx, (u"錨行漂移：" + tag, n, idx)
    assert ORIG[n - 1].count(frag) == 1
    L[n - 1] = ORIG[n - 1] + add
    NEWTXT.append(add)
    print(u"添句 %s @L%d（+%d 字）" % (tag, n, len(add)))


def insert_after(frag, new, tag):
    """在唯一命中 frag 之行之後（其下一行須為空行）插入一段＋一空行。
       呼叫順序必須由大行號到小行號，否則後插者會使前插者之行號失準。"""
    n = line_of(frag, tag)
    assert u"・" not in new and u"！" not in new, (u"禁用字形：" + tag)
    for m in re.finditer(u"「\\*\\*([^」\\n]*)\\*\\*」", new):
        assert _tk.VINAYA.find(_tk.norm(m.group(1))) >= 0, (u"逐字無據：" + tag, m.group(1)[:16])
    assert L[n] == u"", (u"錨後非空行：" + tag, repr(L[n][:30]))
    L[n + 1:n + 1] = [new, u""]
    NEWTXT.append(new)
    print(u"插入 %s @L%d 後 +2 行" % (tag, n))


