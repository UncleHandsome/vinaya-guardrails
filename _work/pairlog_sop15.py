BACKUP = u"列印SOP.pre_a15.md"


def main():
    go = "--write" in sys.argv
    p = os.path.abspath(SOP)
    raw = io.open(p, "rb").read()
    sha = hashlib.sha256(raw).hexdigest()[:12]
    text = raw.decode("utf-8")
    L = text.replace("\r\n", "\n").split("\n")
    k = next((i for i, l in enumerate(L) if l.startswith(MARK)), None)
    if k is None:
        raise SystemExit(u"找不到『%s』之標題" % MARK)
    if u"第十五波・奉終審裁決令" in text:
        print(u"  ・已在帳，不復插")
        return 0
    sys.path.insert(0, os.path.dirname(p))
    new = TXT.rstrip("\n").split("\n")
    os.environ.setdefault("PYTHONIOENCODING", "utf-8")
    try:
        import pairsimp
        bad = [(i + 1, pairsimp.hits(l)) for i, l in enumerate(new) if pairsimp.hits(l)]
    except Exception as e:                       # 共器讀語料需時，失敗不得默過
        raise SystemExit(u"簡形之閘無法開（%s）——無閘不落刀" % e)
    print(u"SOP %d 行・SHA %s・新文 %d 行・簡形命中 %d" % (len(L), sha, len(new), len(bad)))
    for i, h in bad[:8]:
        print(u"      新文第 %d 行 ➔ %s" % (i, h))
    if bad:
        raise SystemExit(u"新文帶簡形，不落刀")
    if not go:
        print(u"（試跑・加 --write 始落盤）")
        return 0
    bd = os.path.join(ROOT, u"..", "_archive", u"備份", u"SOP")
    if not os.path.isdir(bd):
        os.makedirs(bd)
    io.open(os.path.join(bd, BACKUP), "wb").write(raw)
    L[k:k] = new + [u""]
    io.open(p, "wb").write("\n".join(L).encode("utf-8"))
    print(u"  落盤：%d 行・SHA %s ➔ %s" % (len(L), sha,
                                        hashlib.sha256(io.open(p, "rb").read()).hexdigest()[:12]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
